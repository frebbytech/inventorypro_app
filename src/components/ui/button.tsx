
import * as React from "react"
import { Slot } from "@radix-ui/react-slot"
import { cva, type VariantProps } from "class-variance-authority"
import { cn } from "@/lib/utils"

const buttonVariants = cva(
  [
    "inline-flex items-center justify-center gap-2 whitespace-nowrap",
    "rounded-md text-sm font-semibold tracking-wide",
    "transition-all duration-200 ease-in-out",
    "focus-visible:outline-none",
    "focus-visible:ring-2 focus-visible:ring-ring",
    "focus-visible:ring-offset-2",
    "focus-visible:ring-offset-background",
    "disabled:pointer-events-none disabled:opacity-40",
    "[&_svg]:pointer-events-none [&_svg]:size-4 [&_svg]:shrink-0",
  ],
  {
    variants: {
      variant: {
        // Primary CTA
        default:
          "bg-primary text-primary-foreground dark:text-white shadow-sm " +
          "hover:bg-primary/90 active:scale-[0.98]",

        // Destructive / Error Action
        destructive:
          "bg-destructive text-white shadow-sm " +
          "hover:bg-destructive/90 active:scale-[0.98]",

        // Secondary Action
        secondary:
          "bg-secondary text-secondary-foreground " +
          "hover:bg-secondary/80 active:scale-[0.98]",

        // Outline Action
        outline:
          "border border-border bg-background text-foreground " +
          "hover:bg-accent hover:text-accent-foreground " +
          "active:scale-[0.98]",

        // Ghost / Tertiary Action
        ghost:
          "bg-transparent text-foreground " +
          "hover:bg-accent hover:text-accent-foreground " +
          "active:scale-[0.98]",

        // Text Link
        link:
          "bg-transparent text-primary underline-offset-4 " +
          "hover:underline",
      },

      size: {
        // Default: 48px
        default: "h-11 px-6 py-2.5",

        // Compact button
        sm: "h-8 px-4 text-xs",

        // Large CTA
        lg: "h-12 px-10 text-base tracking-wider",

        // Icon-only button
        icon: "h-10 w-10",
      },
    },

    defaultVariants: {
      variant: "default",
      size: "default",
    },
  }
)

export interface ButtonProps
  extends React.ButtonHTMLAttributes<HTMLButtonElement>,
    VariantProps<typeof buttonVariants> {
  asChild?: boolean
}

const Button = React.forwardRef<HTMLButtonElement, ButtonProps>(
  ({ className, variant, size, asChild = false, ...props }, ref) => {
    const Comp = asChild ? Slot : "button"

    return (
      <Comp
        ref={ref}
        className={cn(buttonVariants({ variant, size, className }))}
        {...props}
      />
    )
  }
)

Button.displayName = "Button"

export { Button, buttonVariants }




